/**
 * Bake the Hebrew font the PDF exporter falls back to.
 *
 * Fraunces covers Latin and nothing else, and jsPDF's built-in fonts are
 * WinAnsi-encoded, so a Hebrew guest name used to come out as mojibake — every
 * export, silently, with no error anywhere. This builds a second embedded font
 * so those names render as themselves.
 *
 * Frank Ruhl Libre is the choice because it is a Hebrew serif designed
 * alongside a Latin one, so a guest list that mixes "משפחת כהן" and "Cohen"
 * still looks like one document. Latin is merged in for exactly that reason:
 * mixed names must not need two fonts in the same string.
 *
 * The font package is not a project dependency — it is only needed to
 * regenerate this file, and hebrew.ts is checked in like fraunces.ts so a clean
 * `npm ci && npm run build` needs neither it nor fontTools.
 *
 * Run: npm i -D @fontsource-variable/frank-ruhl-libre
 *      node scripts/build-hebrew-font.mjs
 * Output: src/io/pdf/hebrew.ts (checked in, like fraunces.ts)
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const FILES = 'node_modules/@fontsource-variable/frank-ruhl-libre/files';
const PARTS = ['hebrew', 'latin', 'latin-ext'];
const WEIGHTS = [
  { name: 'regular', wght: 400 },
  { name: 'bold', wght: 600 },
];

// Hebrew letters, final forms, points and the two Hebrew punctuation marks,
// plus the same Latin range Fraunces carries so mixed names stay in one font.
const UNICODES = [
  'U+0020-007E',
  'U+00A0-00FF',
  'U+0100-017F',
  'U+05B0-05C7', // niqqud and cantillation people actually type
  'U+05D0-05EA', // alef to tav, including final forms
  'U+05F0-05F4', // ligatures, geresh, gershayim
  'U+200E,U+200F', // the direction marks, so they survive rather than notdef
  'U+2010-2015',
  'U+2018-201D',
  'U+2026',
].join(',');

const work = mkdtempSync(join(tmpdir(), 'tiktak-hebrew-'));
const py = (code) => execFileSync('python3', ['-c', code], { stdio: ['ignore', 'pipe', 'pipe'] });

function build(weightName, wght) {
  const parts = PARTS.map((part) => join(work, `${weightName}-${part}.ttf`));
  PARTS.forEach((part, i) => {
    py(`
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
f = TTFont("${FILES}/frank-ruhl-libre-${part}-wght-normal.woff2")
f.flavor = None
f = instancer.instantiateVariableFont(f, {"wght": ${wght}}, inplace=True, updateFontNames=False)
f.save(${JSON.stringify(parts[i])})
`);
  });

  const merged = join(work, `${weightName}-merged.ttf`);
  py(`
from fontTools.merge import Merger
Merger().merge([${parts.map((p) => JSON.stringify(p)).join(', ')}]).save(${JSON.stringify(merged)})
`);

  const subset = join(work, `${weightName}-subset.ttf`);
  execFileSync('python3', [
    '-m',
    'fontTools.subset',
    merged,
    `--unicodes=${UNICODES}`,
    '--layout-features=kern',
    '--no-hinting',
    '--drop-tables+=STAT,DSIG',
    `--output-file=${subset}`,
  ]);

  const coverage = py(`
from fontTools.ttLib import TTFont
cm = TTFont(${JSON.stringify(subset)}).getBestCmap()
print(",".join(str(c) for c in sorted(cm)))
`)
    .toString()
    .trim();

  const bytes = readFileSync(subset);
  console.log(
    `${weightName}: ${(bytes.length / 1024).toFixed(1)} kB, ${coverage.split(',').length} codepoints`,
  );
  return { base64: bytes.toString('base64'), coverage };
}

const regular = build('regular', 400);
const bold = build('bold', 600);

// The failure this script exists to prevent: a Hebrew font with no Hebrew in it.
for (const [name, built] of Object.entries({ regular, bold })) {
  const codes = new Set(built.coverage.split(',').map(Number));
  for (const ch of 'אבגדהוזחטיכלמנסעפצקרשת םןץףךCohen 5') {
    if (ch !== ' ' && !codes.has(ch.codePointAt(0))) {
      throw new Error(`${name} subset is missing "${ch}" — the merge step did not work`);
    }
  }
}

const file = `// Generated by scripts/build-hebrew-font.mjs — do not edit by hand.
// Frank Ruhl Libre, instanced at a fixed weight, merged across unicode ranges
// and subset for embedding in exported PDFs. Loaded only when a name needs it.
// SIL Open Font License 1.1: https://fonts.google.com/specimen/Frank+Ruhl+Libre

export const HEBREW_REGULAR = '${regular.base64}';

export const HEBREW_BOLD = '${bold.base64}';

/** Codepoints the embedded subsets can actually draw. */
const COVERAGE = new Set([${regular.coverage}]);

/** Whether this font can draw every character in the string. */
export function hebrewCanRender(text: string): boolean {
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (code !== undefined && !COVERAGE.has(code)) return false;
  }
  return true;
}
`;

writeFileSync('src/io/pdf/hebrew.ts', file);
console.log(`wrote src/io/pdf/hebrew.ts (${(file.length / 1024).toFixed(1)} kB)`);
