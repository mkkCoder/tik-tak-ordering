/**
 * Bake the Fraunces subsets that the PDF exporter embeds.
 *
 * Three things have to happen before jsPDF can use Fraunces:
 *  1. It is a variable font, and jsPDF has no idea what that is — so it is
 *     instanced at a fixed weight first.
 *  2. Fontsource ships it split by unicode range, and the "latin-ext" file
 *     contains no basic Latin at all. Building from that file alone yields a
 *     font with no letters, which jsPDF silently renders as .notdef and drops
 *     from the text layer. So latin and latin-ext are merged.
 *  3. jsPDF embeds a plain TTF, not woff2.
 *
 * The generated module also carries the exact set of codepoints covered, so the
 * exporter can fall back to a built-in font rather than emit a broken name.
 *
 * Run: node scripts/build-pdf-font.mjs
 * Output: src/io/pdf/fraunces.ts (checked in, so `npm ci && npm run build` works)
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const FILES = 'node_modules/@fontsource-variable/fraunces/files';
const PARTS = ['latin', 'latin-ext'];
const WEIGHTS = [
  { name: 'regular', wght: 400 },
  { name: 'bold', wght: 600 },
];

// Latin-1 plus Latin Extended-A and the punctuation real guest lists contain.
const UNICODES = 'U+0020-007E,U+00A0-00FF,U+0100-017F,U+2010-2015,U+2018-201D,U+2026,U+20AC';

const work = mkdtempSync(join(tmpdir(), 'tiktak-font-'));
const py = (code) => execFileSync('python3', ['-c', code], { stdio: ['ignore', 'pipe', 'pipe'] });

function build(weightName, wght) {
  const parts = PARTS.map((part) => join(work, `${weightName}-${part}.ttf`));
  PARTS.forEach((part, i) => {
    py(`
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
f = TTFont("${FILES}/fraunces-${part}-full-normal.woff2")
f.flavor = None
f = instancer.instantiateVariableFont(
    f, {"wght": ${wght}, "SOFT": 0, "WONK": 0, "opsz": 14},
    inplace=True, updateFontNames=False,
)
f.save(${JSON.stringify(parts[i])})
`);
  });

  const merged = join(work, `${weightName}-merged.ttf`);
  py(`
from fontTools.merge import Merger
Merger().merge([${parts.map((p) => JSON.stringify(p)).join(', ')}]).save(${JSON.stringify(merged)})
`);

  const subset = join(work, `${weightName}-subset.ttf`);
  execFileSync('python3', [
    '-m',
    'fontTools.subset',
    merged,
    `--unicodes=${UNICODES}`,
    '--layout-features=kern',
    '--no-hinting',
    '--drop-tables+=STAT,DSIG',
    `--output-file=${subset}`,
  ]);

  const coverage = py(`
from fontTools.ttLib import TTFont
cm = TTFont(${JSON.stringify(subset)}).getBestCmap()
print(",".join(str(c) for c in sorted(cm)))
`)
    .toString()
    .trim();

  const bytes = readFileSync(subset);
  console.log(`${weightName}: ${(bytes.length / 1024).toFixed(1)} kB, ${coverage.split(',').length} codepoints`);
  return { base64: bytes.toString('base64'), coverage };
}

const regular = build('regular', 400);
const bold = build('bold', 600);

// Sanity check: a font with no 'D' is the failure mode this script exists to prevent.
for (const [name, built] of Object.entries({ regular, bold })) {
  const codes = new Set(built.coverage.split(',').map(Number));
  for (const ch of 'DanaYovTble0123') {
    if (!codes.has(ch.charCodeAt(0))) {
      throw new Error(`${name} subset is missing "${ch}" — the merge step did not work`);
    }
  }
}

const file = `// Generated by scripts/build-pdf-font.mjs — do not edit by hand.
// Fraunces, instanced at a fixed weight, merged across unicode ranges and
// subset for embedding in exported PDFs.
// SIL Open Font License 1.1: https://github.com/undercasetype/Fraunces

export const FRAUNCES_REGULAR = '${regular.base64}';

export const FRAUNCES_BOLD = '${bold.base64}';

/** Codepoints the embedded subsets can actually draw. */
const COVERAGE = new Set([${regular.coverage}]);

/**
 * jsPDF stops encoding a string at the first character the font lacks, which
 * would silently truncate a guest's name. Callers check first and fall back to
 * a built-in font when a name falls outside the subset.
 */
export function fraunceCanRender(text: string): boolean {
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (code !== undefined && !COVERAGE.has(code)) return false;
  }
  return true;
}
`;

writeFileSync('src/io/pdf/fraunces.ts', file);
console.log(`wrote src/io/pdf/fraunces.ts (${(file.length / 1024).toFixed(1)} kB)`);
